/**
 * Sitemap lastmod generator.
 *
 * Writes apps/web/content/route-lastmod.generated.ts: for every URL the sitemap
 * lists, the UTC day of the last commit that touched the files that render it
 * (scripts/seo/route-sources.mjs decides which files those are). A file with
 * uncommitted changes counts as changed today, so running this right before a
 * commit dates the edited pages to the day they ship.
 *
 * The map is committed rather than computed during `next build`, because the
 * build may run where there is no full Git history (a shallow CI clone, the
 * Cloudflare build image), and a wrong date is worse than an old one.
 *
 *   pnpm seo:lastmod           regenerate the map
 *   pnpm seo:lastmod --check   exit 1 if the committed map is out of date
 *
 * A unit test fails when an indexable route has no entry, so a new page cannot
 * reach the sitemap without a real date.
 */

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import { shouldNoIndex } from "@tract/seo";
import { indexableRoutes } from "../apps/web/content/routes";
import { sourceFilesForRoute } from "./seo/route-sources.mjs";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const OUTPUT = "apps/web/content/route-lastmod.generated.ts";

function git(args: string[]): string {
  return execFileSync("git", args, { cwd: ROOT, encoding: "utf8" }).trim();
}

function utcDay(date: Date): string {
  return date.toISOString().slice(0, 10);
}

if (git(["rev-parse", "--is-shallow-repository"]) === "true") {
  console.error(
    "seo:lastmod refused: this is a shallow clone, so old files would all date to the\n" +
      "clone boundary. Run `git fetch --unshallow` first."
  );
  process.exit(1);
}

const today = utcDay(new Date());

/** Paths with uncommitted changes, staged or not, including untracked files. */
const dirty = new Set(
  git(["status", "--porcelain", "--untracked-files=all"])
    .split("\n")
    .filter((line) => line.length > 3)
    .map((line) => line.slice(3).split(" -> ").pop() ?? "")
);

const byFileSet = new Map<string, string>();

function lastChangedDay(files: string[]): string {
  if (files.some((file) => dirty.has(file))) return today;
  const key = files.join("\n");
  const cached = byFileSet.get(key);
  if (cached !== undefined) return cached;
  const iso = git(["log", "-1", "--format=%cI", "--", ...files]);
  if (iso === "") throw new Error(`no commit touches ${files.join(", ")}`);
  const day = utcDay(new Date(iso));
  byFileSet.set(key, day);
  return day;
}

const entries: [string, string][] = [];
const unmapped: string[] = [];
for (const route of indexableRoutes()) {
  if (shouldNoIndex(route.path)) continue;
  const files = sourceFilesForRoute(ROOT, route.path);
  if (files.length === 0) {
    unmapped.push(route.path);
    continue;
  }
  entries.push([route.path, lastChangedDay(files)]);
}

if (unmapped.length > 0) {
  console.error(`seo:lastmod: no page file renders ${unmapped.join(", ")}`);
  process.exit(1);
}

const body = [
  "/**",
  " * GENERATED by `pnpm seo:lastmod` (scripts/seo-lastmod.ts). Do not edit by hand.",
  " *",
  " * The UTC day each sitemap URL last changed: the newest commit touching the",
  " * page module or the content modules it renders (scripts/seo/route-sources.mjs).",
  " * Regenerate in the same commit as any content change.",
  " */",
  "export const ROUTE_LASTMOD: Readonly<Record<string, string>> = {",
  ...entries.map(([path, day]) => `  ${JSON.stringify(path)}: ${JSON.stringify(day)},`),
  "};",
  ""
].join("\n");

// The scripts run as CommonJS under tsx, so no top-level await.
async function main(): Promise<void> {
  const outputPath = join(ROOT, OUTPUT);
  const config = (await resolveConfig(outputPath)) ?? {};
  const formatted = await format(body, { ...config, filepath: outputPath });

  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(outputPath, "utf8");
    } catch {
      // A missing map is out of date by definition.
    }
    if (current !== formatted) {
      console.error(`seo:lastmod: ${OUTPUT} is out of date. Run \`pnpm seo:lastmod\`.`);
      process.exit(1);
    }
    console.log(`seo:lastmod: ${entries.length} routes, up to date`);
  } else {
    writeFileSync(outputPath, formatted);
    console.log(`seo:lastmod: wrote ${entries.length} routes to ${OUTPUT}`);
  }
}

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});
